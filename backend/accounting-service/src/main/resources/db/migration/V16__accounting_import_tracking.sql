CREATE TABLE accounting_imports (
    id BIGSERIAL PRIMARY KEY,
    import_type VARCHAR(50) NOT NULL CHECK (import_type IN ('BANK_STATEMENT','INVOICES','JOURNAL_ENTRIES')),
    filename VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PROCESSING','COMPLETED','COMPLETED_WITH_ERRORS','FAILED')),
    total_rows INT NOT NULL DEFAULT 0,
    processed_rows INT NOT NULL DEFAULT 0,
    error_rows INT NOT NULL DEFAULT 0,
    errors JSONB,
    imported_by VARCHAR(150) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
