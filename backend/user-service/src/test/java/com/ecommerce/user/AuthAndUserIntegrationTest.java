package com.ecommerce.user;

import com.ecommerce.user.model.User;
import com.ecommerce.user.repository.UserRepository;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.http.MediaType;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.web.servlet.MockMvc;

import java.util.HashMap;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.*;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@SpringBootTest
@AutoConfigureMockMvc
@ActiveProfiles("test")
public class AuthAndUserIntegrationTest {

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private UserRepository userRepository;

    @Autowired
    private ObjectMapper objectMapper;

    @Autowired
    private PasswordEncoder passwordEncoder;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @BeforeEach
    void setUp() {
        userRepository.deleteAll();
        jdbcTemplate.execute("CREATE TABLE IF NOT EXISTS access_roles (role_key VARCHAR(64) PRIMARY KEY, display_name VARCHAR(120) NOT NULL, hierarchy_level INTEGER NOT NULL, system_role BOOLEAN NOT NULL DEFAULT FALSE)");
        jdbcTemplate.execute("CREATE TABLE IF NOT EXISTS access_permissions (permission_key VARCHAR(120) PRIMARY KEY, module_name VARCHAR(64) NOT NULL, description VARCHAR(240) NOT NULL)");
        jdbcTemplate.execute("CREATE TABLE IF NOT EXISTS access_role_permissions (role_key VARCHAR(64) NOT NULL, permission_key VARCHAR(120) NOT NULL, PRIMARY KEY (role_key, permission_key))");
        jdbcTemplate.execute("CREATE TABLE IF NOT EXISTS access_audit_log (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_user_id BIGINT, actor_email VARCHAR(255), action VARCHAR(64) NOT NULL, target_type VARCHAR(64) NOT NULL, target_id VARCHAR(128) NOT NULL, before_value JSONB, after_value JSONB, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP)");
        jdbcTemplate.update("DELETE FROM access_role_permissions");
        jdbcTemplate.update("DELETE FROM access_permissions");
        jdbcTemplate.update("DELETE FROM access_roles");
        jdbcTemplate.update("DELETE FROM access_audit_log");
        jdbcTemplate.update("INSERT INTO access_roles(role_key, display_name, hierarchy_level, system_role) VALUES('SUPER_ADMIN', 'Super Admin', 1000, TRUE), ('ADMIN', 'Administrator', 800, TRUE), ('MANAGER', 'Manager', 500, TRUE), ('USER', 'Standard User', 100, TRUE)");
        jdbcTemplate.update("INSERT INTO access_permissions(permission_key, module_name, description) VALUES('roles:manage', 'roles', 'Manage delegated roles')");
        jdbcTemplate.update("INSERT INTO access_role_permissions(role_key, permission_key) VALUES('ADMIN', 'roles:manage')");
    }

    @Test
    @DisplayName("POST /api/users/login should authenticate and return JWT token")
    void testLoginSuccess() throws Exception {
        User user = new User();
        user.setEmail("john.doe@ecommerce.com");
        user.setPassword(passwordEncoder.encode("password123"));
        user.setName("John Doe");
        user.setRole("USER");
        user.setActive(true);
        userRepository.save(user);

        Map<String, String> loginRequest = new HashMap<>();
        loginRequest.put("email", "john.doe@ecommerce.com");
        loginRequest.put("password", "password123");

        mockMvc.perform(post("/api/users/login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(loginRequest)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.token").isString())
                .andExpect(jsonPath("$.token").isNotEmpty());

        // Verify user was persisted
        User created = userRepository.findByEmail("john.doe@ecommerce.com").orElse(null);
        assertThat(created).isNotNull();
        assertThat(created.getRole()).isEqualTo("USER");
    }

    @Test
    @org.springframework.security.test.context.support.WithMockUser(username = "jane.doe@ecommerce.com", roles = {"USER"})
    @DisplayName("GET /api/users/{id} should return user profile")
    void testGetUserById() throws Exception {
        User user = new User();
        user.setEmail("jane.doe@ecommerce.com");
        user.setPassword("password123");
        user.setName("Jane Doe");
        user.setRole("USER");
        user.setActive(true);
        User saved = userRepository.save(user);

        mockMvc.perform(get("/api/users/" + saved.getId()))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(saved.getId()))
                .andExpect(jsonPath("$.email").value("jane.doe@ecommerce.com"))
                .andExpect(jsonPath("$.name").value("Jane Doe"))
                .andExpect(jsonPath("$.role").value("USER"));
    }

    @Test
    @org.springframework.security.test.context.support.WithMockUser(username = "bob@ecommerce.com", roles = {"USER"})
    @DisplayName("PUT /api/users/{id} should update display name")
    void testUpdateUserProfile() throws Exception {
        User user = new User();
        user.setEmail("bob@ecommerce.com");
        user.setPassword("password123");
        user.setName("Bob Initial");
        user.setRole("USER");
        user.setActive(true);
        User saved = userRepository.save(user);

        Map<String, String> updateRequest = new HashMap<>();
        updateRequest.put("name", "Bob Updated");

        mockMvc.perform(put("/api/users/" + saved.getId())
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(updateRequest)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.name").value("Bob Updated"));

        User reloaded = userRepository.findById(saved.getId()).orElseThrow();
        assertThat(reloaded.getName()).isEqualTo("Bob Updated");
    }

    @Test
    @org.springframework.security.test.context.support.WithMockUser(username = "admin@ecommerce.com", roles = {"ADMIN"})
    @DisplayName("PUT /api/users/{id}/role should update user role")
    void testUpdateUserRole() throws Exception {
        User user = new User();
        user.setEmail("charlie@ecommerce.com");
        user.setPassword("password123");
        user.setName("Charlie");
        user.setRole("USER");
        user.setActive(true);
        User saved = userRepository.save(user);

        Map<String, String> roleRequest = new HashMap<>();
        roleRequest.put("role", "MANAGER");

        mockMvc.perform(put("/api/users/" + saved.getId() + "/role")
                        .contentType(MediaType.APPLICATION_JSON)
                        .header("X-User-Roles", "ADMIN")
                        .header("X-User-Id", "99")
                        .header("X-User-Email", "admin@ecommerce.com")
                        .content(objectMapper.writeValueAsString(roleRequest)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.role").value("MANAGER"));

        User reloaded = userRepository.findById(saved.getId()).orElseThrow();
        assertThat(reloaded.getRole()).isEqualTo("MANAGER");
    }

    @Test
    @DisplayName("POST /api/users/login should reject deactivated user with 403 Forbidden")
    void testDeactivatedUserLogin() throws Exception {
        User user = new User();
        user.setEmail("disabled@ecommerce.com");
        user.setPassword(passwordEncoder.encode("password123"));
        user.setName("Disabled User");
        user.setRole("USER");
        user.setActive(false);
        userRepository.save(user);

        Map<String, String> loginRequest = new HashMap<>();
        loginRequest.put("email", "disabled@ecommerce.com");
        loginRequest.put("password", "password123");

        mockMvc.perform(post("/api/users/login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(loginRequest)))
                .andExpect(status().isForbidden())
                .andExpect(jsonPath("$.error").value("Account is deactivated"));
    }
}
